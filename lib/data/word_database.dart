  /// All distinct categories in the database.
  static List<String> get categories =>
      allWords.map((w) => w.category).toSet().toList()..sort();

  /// Word count for a specific category.
  static int getWordCountForCategory(String category) {
    return allWords.where((w) => w.category == category).length;
  }

  /// Total word count for a set of categories.
  static int getWordCountForCategories(Set<String> categories) {
    if (categories.isEmpty) return 0;
    return allWords.where((w) => categories.contains(w.category)).length;
  }

  /// Words filtered by category or category set.
  static List<Word> getWords({String? category, Set<String>? categories}) {
    return allWords.where((w) {
      if (category != null && w.category != category) return false;
      if (categories != null &&
          categories.isNotEmpty &&
          !categories.contains(w.category)) {
        return false;
      }
      return true;
    }).toList();
  }

  /// Words filtered by a set of categories.
  static List<Word> getWordsForCategories({Set<String>? categories}) {
    return getWords(categories: categories);
  }
